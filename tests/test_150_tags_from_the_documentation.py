"""Теги из документации не должны приезжать буквами (задача 13.12).

Владелец предложил чинить формат промптом и показал свой рабочий промпт для
n8n: там ответ строится блоками `sendRichMessage` — `<h1>`, `<p>`,
`<blockquote>`, `<table>` с `<thead>`/`<tbody>`, `<hr>`, — и `<br>` прямо
запрещён.

Промпт для НАШЕГО сервиса так устроить нельзя: `telegram_markup` в первых
строках говорит почему — «промпт не гарантия, формат ответа — обязанность
доставки», а промпты пишут пользователи, которым знать подмножество Bot API
неоткуда. Но пример вскрыл настоящий дефект, и он серьёзнее вопроса о
промптах.

**Неизвестный тег у нас не выбрасывается, а экранируется** — и это верно:
пусть автор видит, что модель написала что-то не то, чем текст молча
исчезнет. Беда в том, что список известных тегов уже документации Bot API:
`<p>`, `<hr>`, `<thead>` и `<tbody>` в нём есть, а у нас их не было. Человек,
написавший промпт ПО ДОКУМЕНТАЦИИ TELEGRAM, получал в сообщении буквальные
`<p>` и `</p>`.

Косвенная улика лежала в коде с 9.19: `rich_html_to_plain` разворачивает
`thead` и `tbody` на запасном пути — то есть разворот тегов, которые фильтр
до него не пропускал никогда.
"""

import pytest

from app.services.telegram_markup import rich_html_to_plain, to_telegram_html

# Фрагмент в точности той формы, которую задаёт промпт владельца.
SCRIPT = (
    "<h1>Как перестать тонуть в рутине</h1>"
    "<p><strong>Механика хука:</strong> вопрос-провокация</p>"
    "<blockquote>Ты уверен, что работаешь? Или просто занят?</blockquote>"
    "<table><thead><tr><th>Время</th><th>В кадре</th></tr></thead>"
    "<tbody><tr><td>0:00–0:03</td><td>крупный план</td></tr></tbody></table>"
    "<hr>"
    "<p>Подпишись.</p>"
)


@pytest.mark.parametrize("tag", ["<p>", "<hr>", "<thead>", "<tbody>"])
def test_a_documented_tag_is_not_shown_as_text(tag):
    """Тег из документации Bot API обязан доехать тегом, а не буквами."""
    out = to_telegram_html(SCRIPT)
    escaped = tag.replace("<", "&lt;").replace(">", "&gt;")
    assert escaped not in out, f"{tag} приедет в сообщение буквами: {out[:200]!r}"
    assert tag in out, f"{tag} исчез вместе со смыслом: {out[:200]!r}"


def test_an_unknown_tag_is_still_shown_as_text():
    """Антивакуум: список расширен, а не отменён.

    `<div>` в наборе Bot API нет ни в каком виде. Он и раньше приезжал
    буквами намеренно: пусть автор промпта видит, что модель написала не то,
    чем текст молча исчезнет.
    """
    out = to_telegram_html("<div>текст</div>")
    assert "&lt;div&gt;" in out, f"чужой тег пропущен внутрь: {out!r}"


def test_paragraphs_do_not_collapse_into_one_line():
    """`<p>` — блок: между абзацами не должно появиться ни склейки, ни пустот."""
    out = to_telegram_html("<p>Первый</p>\n<p>Второй</p>")
    assert out == "<p>Первый</p><p>Второй</p>", f"абзацы разъехались: {out!r}"


def test_the_plain_path_unwraps_the_new_tags():
    """`sendMessage` этих тегов не знает — на запасном пути они разворачиваются."""
    plain = rich_html_to_plain(to_telegram_html(SCRIPT))
    for tag in ("<p>", "</p>", "<hr>", "<thead>", "<tbody>"):
        assert tag not in plain, f"на запасной путь ушёл {tag}: {plain[:200]!r}"
    assert "Подпишись." in plain, f"текст потерян при развороте: {plain!r}"
    assert "Механика хука" in plain and "крупный план" in plain, (
        f"содержимое абзаца или таблицы потеряно: {plain!r}"
    )
