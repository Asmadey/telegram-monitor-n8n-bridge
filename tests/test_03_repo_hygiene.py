"""Задача 0.5 — в репозитории нет мусора и дублей.

FastAPI/Ruby/ — вторая копия Rails-шаблона внутри Python-проекта (живой образец
остаётся в Teleton/Ruby/). Teleton/storage.db — пустой файл-дубль: приложение
однажды запишет данные не туда. monitors.json.bak — остаток старой миграции.

О путях. Корень репозитория git — каталог приложения; REPO вычисляется от файла
теста, а не от имени каталога.

**Переписано 2026-09-10, когда дерево развернули.** До этого дня локальная
раскладка была `Teleton/FastAPI` — репозиторий лежал ВНУТРИ рабочего каталога, и
две проверки смотрели на каталог ВЫШЕ репозитория: там заводились пустой
`storage.db`-двойник и конкурирующая копия `PLAN.md`. В CI такого каталога нет,
поэтому обе честно писали skip.

После разворачивания каталог выше репозитория (`AntiGravity/`) к проекту
отношения не имеет, и обе проверки молча ушли в вечный skip — тест перестал
проверять хоть что-нибудь, не покраснев. Это ровно тот отказ, который здесь
ловят. Обе угрозы никуда не делись, они сменили адрес: пустой дубль базы и
полная копия плана теперь заводятся В КОРНЕ репозитория. Проверки переписаны на
корень и работают везде, включая CI, — то есть стали строже, а не слабее.
"""

from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]  # корень репозитория = корень проекта

GONE = [
    REPO / "Ruby",  # дубль Rails-шаблона внутри приложения
    REPO / "monitors.json.bak",  # остаток старой миграции
]

PLAN = REPO / "docs" / "PLAN.md"


def test_junk_paths_do_not_exist():
    survivors = [str(p.relative_to(REPO)) for p in GONE if p.exists()]
    assert not survivors, f"В репозитории остался мусор: {survivors}"


def test_no_empty_duplicate_db_anywhere_in_the_tree():
    """Пустой `storage.db`-двойник: приложение однажды запишет данные не туда.

    Раньше двойник заводился ЭТАЖОМ ВЫШЕ репозитория и проверка смотрела туда.
    После разворачивания дерева (2026-09-10) этажа выше нет — двойник теперь
    заведётся внутри, поэтому ищем по всему дереву, а не по одному пути.
    Живой файл лежит в корне и не пуст; всё остальное с этим именем — ошибка.
    """
    live = REPO / "storage.db"
    # `private-backups/` — намеренный архив с датой в имени: туда кладут снимок
    # перед опасной операцией, и приложение туда не смотрит. Первый прогон этой
    # проверки нашёл именно его — исключение добавлено осознанно, а не чтобы
    # покрасить тест в зелёный. Опасен безымянный дубль рядом с рабочими
    # файлами, а не подписанная резервная копия.
    SAFE = {".venv", ".git", "private-backups"}
    duplicates = [
        db for db in REPO.rglob("storage.db") if db != live and not SAFE & set(db.parts)
    ]
    assert not duplicates, (
        "рядом с живой базой появился двойник — приложение однажды запишет "
        f"данные не туда: {[str(d.relative_to(REPO)) for d in duplicates]}"
    )


def test_app_storage_db_is_the_real_one():
    """Живая база не пуста — защита от уборки не того файла в задаче 0.5.

    Файл в .gitignore, поэтому в чекауте CI его нет: там проверять нечего.
    """
    db = REPO / "storage.db"
    if not db.exists():
        pytest.skip("storage.db отсутствует (gitignore) — нечего проверять")
    assert db.stat().st_size > 0, "storage.db пуст — удалён/затёрт не тот файл"


